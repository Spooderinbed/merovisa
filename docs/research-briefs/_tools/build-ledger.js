#!/usr/bin/env node
/**
 * Sole generator of findings-ledger.md + findings-clusters.md, built FROM the
 * committed findings/*.jsonl (the source of truth post-extraction). Reads whatever
 * `status` each finding currently has — does NOT touch Research Documents/.
 * Run: node docs/research-briefs/_tools/build-ledger.js
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..", "..", "..");
const OUT = path.join(ROOT, "docs", "research-briefs", "findings");
const LEDGER = path.join(ROOT, "docs", "research-briefs", "findings-ledger.md");
const CONFLICTS = path.join(ROOT, "docs", "research-briefs", "findings-clusters.md");

const all = [];
for (const f of fs.readdirSync(OUT).filter((f) => f.endsWith(".jsonl")).sort()) {
  for (const line of fs.readFileSync(path.join(OUT, f), "utf8").split(/\r?\n/)) {
    if (line.trim()) all.push(JSON.parse(line));
  }
}

const groups = {};
for (const r of all) {
  const key = r.category + "|" + (r.entity || "").toLowerCase().trim() + "|" + (r.attribute || "").toLowerCase().trim();
  (groups[key] = groups[key] || []).push(r);
}
let gid = 0;
const collisions = [];
for (const [key, rs] of Object.entries(groups)) {
  const parts = key.split("|");
  if (rs.length < 2 || (!parts[1] && !parts[2])) continue;
  gid++;
  const differ = new Set(rs.map((r) => (r.claim || "").trim())).size > 1;
  rs.forEach((r) => (r.dup_group = "G" + gid));
  collisions.push({ gid: "G" + gid, key, rows: rs, differ });
}

const esc = (s) => (s || "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + "…" : s);
const byStatus = {};
all.forEach((r) => (byStatus[r.status] = (byStatus[r.status] || 0) + 1));

let led = "# Findings ledger (generated)\n\n";
led += "> Generated by `_tools/build-ledger.js` from findings/*.jsonl. Edit `status` in the JSONL, then regenerate.\n\n";
led += `**Total findings:** ${all.length}  ·  **entity+attr clusters:** ${collisions.length}\n\n`;
led += "**Status:** " + Object.entries(byStatus).map(([k, v]) => `${k}=${v}`).join(" · ") + "\n\n";
led += "| ID | topic | conf | type | cluster | status | target | claim |\n";
led += "|----|-------|------|------|---------|--------|--------|-------|\n";
for (const r of all) {
  led += `| ${r.id} | ${r.topic} | ${r.confidence} | ${r.claim_type} | ${r.dup_group || ""} | ${r.status} | ${esc(r.target)} | ${esc(clip(r.claim || "", 110))} |\n`;
}
fs.writeFileSync(LEDGER, led);

let cf = "# Entity+attribute clusters (generated, triage worksheet)\n\n";
cf += "Rows sharing `category + entity + attribute`. Each member carries a `cluster_triage` (enumeration | contradiction | duplicate). Contradictions also set `conflict_with` and are enforced by the conflict gate (reconcile pass-3): a contradiction may ship at most one `used` member.\n\n";
const needReview = collisions.filter((c) => c.differ);
const triageCount = {};
for (const c of collisions) for (const r of c.rows) {
  const t = r.cluster_triage || "untriaged";
  triageCount[t] = (triageCount[t] || 0) + 1;
}
const contradictionClusters = collisions.filter((c) => c.rows.some((r) => r.cluster_triage === "contradiction"));
const untriaged = collisions.filter((c) => c.rows.some((r) => !r.cluster_triage));
cf += `**${collisions.length}** clusters · **${needReview.length}** multi-valued · member triage: ${Object.entries(triageCount).map(([k, v]) => `${k}=${v}`).join(" · ")}\n\n`;
if (contradictionClusters.length) {
  cf += `**Contradictions (${contradictionClusters.length}):** ${contradictionClusters.map((c) => c.gid).join(", ")} — each must resolve to exactly one \`used\` member (rest \`rejected:<reason>\`).\n\n`;
}
if (untriaged.length) {
  cf += `**⚠ Untriaged clusters (${untriaged.length}):** ${untriaged.map((c) => c.gid).join(", ")} — label every member's \`cluster_triage\`.\n\n`;
}
const triLabel = (c) => [...new Set(c.rows.map((r) => r.cluster_triage || "untriaged"))].join("+");
for (const c of collisions.sort((a, b) => Number(b.differ) - Number(a.differ))) {
  const p = c.key.split("|");
  cf += `### ${c.gid} [${triLabel(c)}] — [${p[0]}] ${p[1]} / ${p[2]}\n\n`;
  for (const r of c.rows) {
    const cw = r.conflict_with ? ` ⇄ ${Array.isArray(r.conflict_with) ? r.conflict_with.join(",") : r.conflict_with}` : "";
    cf += `- \`${r.id}\` _${r.cluster_triage || "untriaged"}_${cw} (${r.confidence}/${r.publisher}, ${r.source_date}) ${esc(clip(r.claim || "", 160))}\n`;
  }
  cf += "\n";
}
fs.writeFileSync(CONFLICTS, cf);

const used = byStatus.used || 0;
console.log(`ledger rebuilt: ${all.length} findings · used=${used} · pending=${byStatus.pending || 0} · clusters=${collisions.length}`);
